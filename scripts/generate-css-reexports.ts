/*
 * THE CSS A BINDING PACKAGE RE-EXPORTS, so a project installs `@skryensya/react` (or `vanilla`) and
 * nothing else: `node scripts/generate-css-reexports.ts <package-dir> [--check]`.
 *
 * The JavaScript already reaches core, because the bindings depend on it. The stylesheets are the gap:
 * with a strict `node_modules` (pnpm) a dependency's own dependency is not importable from the app, so
 * `@import "@skryensya/core/components/button.css"` fails unless the app installed core itself. A
 * stub inside the binding fixes that without copying a byte of CSS:
 *
 *     @skryensya/react/css/components/button.css   ->   @import "@skryensya/core/components/button.css";
 *
 * A bundler resolves that inner import from the stub's own directory, where core IS a dependency, so
 * the app never needs to know core exists. The path under `css/` mirrors core's, one for one.
 *
 * `--check` rewrites nothing and fails when a stub is missing, stale or left over, which is what keeps
 * a new component stylesheet from shipping without its stub.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const core = join(root, "packages/core");

/** The folders of core's source CSS a project imports from, each as `css/<folder>/*.css`. */
const SOURCE_FOLDERS = ["components", "patterns", "effects", "fonts"];
/** Built files core exports at its root and under `dimensions/`. */
const BUILT = ["tokens.css", "skryensya.css", "dimensions/radius.css", "dimensions/press-scale.css"];

const cssFiles = (dir: string): string[] =>
  existsSync(dir) ? readdirSync(dir).filter((name) => name.endsWith(".css") && !name.startsWith("_") && statSync(join(dir, name)).isFile()).sort() : [];

/** Every path (relative to core's package root export names) that gets a stub. */
export function reexportedPaths(): string[] {
  const paths = [...BUILT];
  for (const folder of SOURCE_FOLDERS) for (const file of cssFiles(join(core, "css", folder))) paths.push(`${folder}/${file}`);
  return paths.sort();
}

const stub = (path: string) =>
  `/* Re-exports @skryensya/core/${path} so a project that installs only this package can import it.\n * Generated by scripts/generate-css-reexports.ts. Do not edit. */\n@import "@skryensya/core/${path}";\n`;

const walk = (dir: string): string[] =>
  existsSync(dir) ? readdirSync(dir).flatMap((name) => (statSync(join(dir, name)).isDirectory() ? walk(join(dir, name)) : [join(dir, name)])) : [];

export function plan(packageDir: string) {
  const out = join(packageDir, "css");
  const wanted = new Map(reexportedPaths().map((path) => [join(out, path), stub(path)]));
  const present = new Set(walk(out));
  const problems: string[] = [];
  for (const [file, content] of wanted) {
    if (!existsSync(file)) problems.push(`missing ${relative(packageDir, file)}`);
    else if (readFileSync(file, "utf8") !== content) problems.push(`stale   ${relative(packageDir, file)}`);
  }
  for (const file of present) if (!wanted.has(file)) problems.push(`extra   ${relative(packageDir, file)}`);
  return { out, wanted, present, problems };
}

if (import.meta.main) {
  const dir = process.argv[2];
  if (!dir) throw new Error("usage: node scripts/generate-css-reexports.ts <package-dir> [--check]");
  const packageDir = resolve(dir);
  const { wanted, present, problems } = plan(packageDir);
  if (process.argv.includes("--check")) {
    if (problems.length) {
      console.error(`✗ ${relative(root, packageDir)}/css is out of date:\n  ${problems.join("\n  ")}\nRun: node scripts/generate-css-reexports.ts ${relative(root, packageDir)}`);
      process.exit(1);
    }
    console.log(`✓ ${relative(root, packageDir)}/css re-exports ${wanted.size} stylesheets, all current`);
  } else {
    for (const file of present) if (!wanted.has(file)) rmSync(file);
    for (const [file, content] of wanted) {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, content);
    }
    console.log(`✓ ${relative(root, packageDir)}/css: ${wanted.size} stylesheets re-exported`);
  }
}
