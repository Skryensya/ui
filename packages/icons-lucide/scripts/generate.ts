/*
 * Generates the Lucide set from the library.
 *
 * WHY THERE IS CODEGEN HERE AND NOT IN THE MANIFEST. Decision 15 rejected the manifest generator
 * because the allowlist reimplements the bundler's tree-shaking: delete it and the consumer writes an
 * object literal, with no complexity reappearing. This generator is a different thing: it converts the
 * library's format to IconData. Delete it and complexity DOES reappear: the consumer parses SVG at
 * runtime, or ties itself to `?raw`, which is Vite's and not the ecosystem's. Same test, falling the
 * other way.
 *
 * And the result pays twice: the library stays a devDependency, so the consumer's bundle receives 32
 * icons of data and ZERO Lucide runtime.
 *
 * The shell (--check, the emitted template) is shared by all three sets and lives in
 * @skryensya/core/emit-icon-set. What is left here is only what varies: the MAP, the ATTRS, the header,
 * and how ONE name resolves to geometry. Lucide is the data-shaped adapter: the library hands back
 * nodes, not `.svg` files, so its `resolve` serializes the children instead of reading and extracting a
 * file (which is what Phosphor and Material do).
 */
