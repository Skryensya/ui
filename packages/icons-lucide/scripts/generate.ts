/* Lucide's `<svg>` defaults. They go in attrs and not in the CSS because a CSS declaration beats a
 * presentation attribute: a `fill: currentColor` in patterns/icon.css would turn this whole set solid,
 * and it is an outline set. */
const ATTRS = {
  fill: "none",
  stroke: "currentColor",
  "stroke-width": "2",
  "stroke-linecap": "round",
  "stroke-linejoin": "round",
};

const HEADER = `/*
 * GENERATED by scripts/generate.ts, do not edit by hand.
 *
 * Lucide geometry (ISC), redistributed under its license. See LICENSE-lucide.
 */`;

/** Lucide hands back `[["path", {d}], ["circle", {...}]]`, data, not markup. We serialize the children. */
const toBody = (nodes: (typeof icons)[keyof typeof icons]) =>
  nodes
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(" ")} />`)
    .join("");

/** Lucide's adapter: the geometry is data, and the library's viewBox is always `0 0 24 24`. */
const resolve = (name: string, role: string) => {
  const nodes = icons[name as keyof typeof icons];
  if (!nodes) throw new Error(`Lucide no tiene "${name}" (rol "${role}"), ¿se renombró en un upgrade?`);
  return { viewBox: "0 0 24 24", body: toBody(nodes) };
};

generateIconSet({ dir: import.meta.dirname, label: "lucide", map: MAP, attrs: ATTRS, header: HEADER, resolve });
