/* Phosphor draws FILLED shapes, not strokes, even at the `regular` weight, which looks like outline but
 * is filled outlines. Its SVGs already carry fill="currentColor" on the root; we re-declare it here
 * anyway so IconData is explicit and does not depend on the asset staying the same. */
const ATTRS = { fill: "currentColor" };

const WEIGHT = "regular";

const HEADER = `/*
 * GENERATED by scripts/generate.ts, do not edit by hand.
 *
 * Phosphor Icons geometry (MIT), "${WEIGHT}" weight, redistributed under its license.
 * See LICENSE-phosphor.
 */`;

/** Phosphor's adapter: resolve the `.svg` asset from the devDependency and extract its body. */
const resolve = (name: string, role: string) => {
  const spec = `@phosphor-icons/core/assets/${WEIGHT}/${name}.svg`;
  let path;
  try {
    path = fileURLToPath(import.meta.resolve(spec));
  } catch {
    throw new Error(`Phosphor no tiene "${name}" (rol "${role}"), ¿se renombró en un upgrade?`);
  }
  return extractSvgBody(readFileSync(path, "utf8"), name);
};

generateIconSet({ dir: import.meta.dirname, label: "phosphor", map: MAP, attrs: ATTRS, header: HEADER, resolve });
