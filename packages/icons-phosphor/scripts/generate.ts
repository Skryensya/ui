/*
 * Generates the Phosphor set from the library's assets.
 *
 * Phosphor does not publish data: it publishes `.svg` files (`assets/regular/*.svg`). That is why there
 * is a generator here and none for the manifest, see decision 15. The allowlist reimplemented the
 * bundler's tree-shaking and did nothing; this converts a format no bundler converts on its own. Delete
 * it and the consumer parses SVG at runtime or ties itself to `?raw`, which is Vite's. The complexity
 * reappears, so the layer does something.
 *
 * The library stays a devDependency: the consumer's bundle receives 32 icons and nothing else.
 *
 * The shell (--check, the template, the `<svg>` extraction) is shared by all three sets and lives in
 * @skryensya/core/emit-icon-set. What is left here is only what varies: the MAP, the ATTRS, the header,
 * and the asset spec. `resolve` runs in THIS module on purpose: `import.meta.resolve` has to see
 * Phosphor's devDependency, which core does not have.
 */
