/**
 * Makes `data-motion="reduced"` (the app's own reduced-motion choice) reach component CSS.
 *
 * An attribute cannot switch a media query on, so every `@media (prefers-reduced-motion: …)` block in
 * a sheet needs a sibling the attribute can trigger. This script owns those siblings, so the source of
 * truth stays the media block and nothing is hand-copied:
 *
 *   reduce         the block is MIRRORED right below it, same body, under
 *                  `:where(:root[data-motion="reduced"])`. `:where()` adds no specificity, so the
 *                  mirror wins and loses against the same rules the media block does.
 *   no-preference  the block opts INTO motion, so the attribute must opt back out: its body is wrapped
 *                  in `:where(:root:not([data-motion="reduced"]))`.
 *
 * The media query is always left as it was, so a browser that ignored the mirror still honours the
 * system setting. The attribute only ever ADDS reduction.
 *
 *   node scripts/mirror-motion.ts            rewrite the sheets
 *   node scripts/mirror-motion.ts --check    fail if any sheet is out of date (runs in `check`)
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const CSS = join(import.meta.dirname, "..", "css");
const DIRS = ["components", "patterns", "effects"];

const MIRROR_OPEN = "/* data-motion mirror (generated by scripts/mirror-motion.ts, edit the @media block above) */";
const MIRROR_CLOSE = "/* end data-motion mirror */";
const MIRROR_SEL = `:where(:root[data-motion="reduced"])`;
const GUARD_SEL = `:where(:root:not([data-motion="reduced"]))`;

/** Same length as the input, with comments blanked, so offsets found in it index the real text. */
const blank = (s: string) => s.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "));

/** Offset just past the `}` that closes the block whose `{` is at `open`. */
function closeOf(scan: string, open: number): number {
  let depth = 0;
  for (let i = open; i < scan.length; i++) {
    if (scan[i] === "{") depth++;
    else if (scan[i] === "}" && --depth === 0) return i + 1;
  }
  throw new Error("unbalanced braces");
}

/** Strips every generated mirror, so a run always starts from the hand-written source. */
function withoutMirrors(src: string): string {
  const re = new RegExp(`\\n\\n[ \\t]*${escape(MIRROR_OPEN)}[\\s\\S]*?${escape(MIRROR_CLOSE)}`, "g");
  return src.replace(re, "");
}
const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");

export function transform(source: string): string {
  let src = withoutMirrors(source);
  const media = /@media\s*([^{]*prefers-reduced-motion\s*:\s*(reduce|no-preference)[^{]*)\{/g;
  // Work from the last block to the first, so earlier offsets stay valid while text is inserted.
  const found: { start: number; open: number; end: number; kind: string }[] = [];
  const scan = blank(src);
  for (let m; (m = media.exec(scan)); ) {
    const open = m.index + m[0].length - 1;
    found.push({ start: m.index, open, end: closeOf(scan, open), kind: m[2] });
  }
  for (const b of found.reverse()) {
    const lineStart = src.lastIndexOf("\n", b.start) + 1;
    const indent = src.slice(lineStart, b.start);
    if (/\S/.test(indent)) throw new Error(`a prefers-reduced-motion block shares a line with other CSS near offset ${b.start}`);
    const body = src.slice(b.open + 1, b.end - 1); // text between the braces, newlines included
    if (b.kind === "reduce") {
      const mirror = `\n\n${indent}${MIRROR_OPEN}\n${indent}${MIRROR_SEL} {${body}}\n${indent}${MIRROR_CLOSE}`;
      src = src.slice(0, b.end) + mirror + src.slice(b.end);
    } else if (!blank(body).trimStart().startsWith(GUARD_SEL)) {
      const rules = body.replace(/^\n/, "").replace(/\s+$/, "");
      const nested = rules.split("\n").map((l) => (l.trim() ? `  ${l}` : l)).join("\n");
      const guarded = `\n${indent}  ${GUARD_SEL} {\n${nested}\n${indent}  }\n${indent}`;
      src = src.slice(0, b.open + 1) + guarded + src.slice(b.end - 1);
    }
  }
  return src;
}

const files = DIRS.flatMap((d) =>
  readdirSync(join(CSS, d))
    .filter((f) => f.endsWith(".css"))
    .map((f) => join(CSS, d, f)),
);

const check = process.argv.includes("--check");
const stale: string[] = [];
for (const file of files) {
  const before = readFileSync(file, "utf8");
  const after = transform(before);
  if (after === before) continue;
  stale.push(file.slice(CSS.length + 1));
  if (!check) writeFileSync(file, after);
}

if (check && stale.length) {
  console.error(`✗ data-motion mirrors out of date in ${stale.length} sheet(s), run \`node scripts/mirror-motion.ts\`:\n  ${stale.join("\n  ")}`);
  process.exit(1);
}
console.log(check ? "✓ data-motion mirrors are current" : `✓ data-motion mirrors written in ${stale.length} sheet(s)`);
