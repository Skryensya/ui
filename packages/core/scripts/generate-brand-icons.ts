/*
 * Writes src/iconify-brands.ts: which drawing each mapped Iconify collection gives every `brand-*` mark
 * (icon.ts), found by the names collections use for logos, and Tabler's drawing (MIT) as the fallback a
 * collection without that logo gets. Run after adding a brand to `brandIconNames` or a collection:
 *   node scripts/generate-brand-icons.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { brandIconNames } from "../src/icon.ts";

const require = createRequire(import.meta.url);
type Json = { prefix: string; icons: Record<string, { body: string; width?: number; height?: number }>; aliases?: Record<string, { parent: string }>; width?: number; height?: number };
const load = (prefix: string): Json => JSON.parse(readFileSync(require.resolve(`@iconify-json/${prefix}/icons.json`), "utf8"));

const prefixes = ["lucide", "tabler", "ph", "ri", "mdi", "material-symbols", "solar", "heroicons", "iconoir", "mingcute", "carbon", "fluent", "bi", "hugeicons"];

/* The names collections give a logo, most specific first. `x` is also Twitter's old name in some sets. */
function candidates(prefix: string, brand: string): string[] {
  const own: Record<string, string[]> = {
    tabler: [`brand-${brand}`],
    ph: [`${brand}-logo`],
    ri: [`${brand}-line`, `${brand}-fill`],
    carbon: [`logo-${brand}`],
    mingcute: [`${brand}-line`, `social-${brand}-line`],
    fluent: [`${brand}-24-regular`],
    solar: [`${brand}-linear`, `${brand}-bold`],
    hugeicons: [brand, `${brand}-01`],
  };
  /* `apple` alone is the fruit in most collections, and Hugeicons' `apple-01` too: MDI and Bootstrap are the two whose bare name is the logo. */
  if (brand === "apple") return [...(prefix === "hugeicons" ? [] : (own[prefix] ?? []).filter((name) => name !== "apple")), "apple-logo", "logo-apple", "brand-apple", ...(prefix === "mdi" || prefix === "bi" ? ["apple"] : [])];
  /* `x` alone is a close mark in most collections (Lucide's, Bootstrap's), never the logo: only the logo's own names. */
  if (brand === "x") return [...(own[prefix] ?? []).filter((name) => name !== "x"), "x-logo", "logo-x", "brand-x", "twitter-x", "twitter-x-line", "social-x-line", "new-twitter"];
  return [...(own[prefix] ?? []), brand, `${brand}-logo`, `logo-${brand}`, `brand-${brand}`];
}

/* Collections with (almost) no logos: a stray match would be the only brand drawn in their style, so they take the fallback for all. */
const noBrands = new Set(["material-symbols", "solar", "heroicons", "fluent"]);

const maps: Record<string, Record<string, string>> = {};
for (const prefix of prefixes) {
  const json = load(prefix);
  const has = (name: string) => Boolean(json.icons[name] || json.aliases?.[name]);
  maps[prefix] = {};
  if (noBrands.has(prefix)) continue;
  for (const role of brandIconNames) {
    const brand = role.slice("brand-".length);
    const found = candidates(prefix, brand).find(has);
    if (found) maps[prefix][role] = found;
  }
}

const tabler = load("tabler");
const fallback: Record<string, { viewBox: string; body: string; attrs: Record<string, string> }> = {};
for (const role of brandIconNames) {
  const name = `brand-${role.slice("brand-".length)}`;
  const icon = tabler.icons[name] ?? tabler.icons[tabler.aliases?.[name]?.parent ?? ""];
  if (!icon) throw new Error(`tabler has no ${name}: pick another fallback for ${role}`);
  fallback[role] = {
    viewBox: `0 0 ${icon.width ?? tabler.width ?? 24} ${icon.height ?? tabler.height ?? 24}`,
    body: icon.body,
    attrs: { fill: "none", stroke: "currentColor", "stroke-width": "2", "stroke-linecap": "round", "stroke-linejoin": "round" },
  };
}

const out = `/*
 * GENERATED by scripts/generate-brand-icons.ts: do not edit by hand.
 *
 * The \`brand-*\` marks (icon.ts): per collection, the name of each logo it draws, so a set's GitHub has the
 * set's own stroke; and \`brandFallback\`, Tabler's drawings (MIT), for the logos a collection does not have.
 */
import type { BrandIconName, IconData } from "./icon.js";

export const brandMaps: Record<string, Partial<Record<BrandIconName, string>>> = ${JSON.stringify(maps, null, 2)};

export const brandFallback: Record<BrandIconName, IconData> = ${JSON.stringify(fallback, null, 2)};
`;
writeFileSync(new URL("../src/iconify-brands.ts", import.meta.url), out);
console.log(`iconify-brands.ts: ${brandIconNames.length} brands, ${prefixes.map((p) => `${p} ${Object.keys(maps[p]!).length}`).join(", ")}`);
