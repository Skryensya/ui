import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { iconSetCss, iconSetFromIconify, iconSetModule, iconifyPresets, type IconifyJSON } from "@skryensya/core/iconify";
import type { Context } from "../context.js";

export type IconsOptions = {
  /** Path without extension: `src/icons` writes `src/icons.ts` and `src/icons.css`. */
  out?: string;
  /** Fail if the written files are stale instead of writing them. */
  check?: boolean;
  /** Also write the `component-*` marks, for an app that lists the kit's components. */
  components?: boolean;
  /** Print how to bind the set. `add` prints its own setup instead. */
  usage?: boolean;
};

/*
 * The icon set is the project's dependency, never the kit's: the project installs `@iconify-json/<prefix>`
 * (a dev dependency, it is read at build time) and this writes the ~76 roles the components ask for into
 * the project. Only those reach the bundle; the library's other thousands of icons stay in node_modules.
 */
export function icons(prefix: string | undefined, options: IconsOptions, ctx: Context): number {
  const preset = prefix ? iconifyPresets[prefix] : undefined;
  if (!preset) {
    ctx.error(`${prefix ? `No mapped set "${prefix}".` : "Say which set."} Mapped: ${Object.keys(iconifyPresets).join(", ")}.`);
    ctx.error("Any other Iconify set works with your own map: iconSetFromIconify(json, { map }) from @skryensya/core/iconify.");
    return 1;
  }

  const spec = `@iconify-json/${preset.prefix}/icons.json`;
  const path = findUp(resolve(ctx.cwd), join("node_modules", spec));
  if (!path) {
    ctx.error(`${spec} is not installed in ${ctx.cwd}. Install it as a dev dependency: pnpm add -D @iconify-json/${preset.prefix}`);
    return 1;
  }
  const json = JSON.parse(readFileSync(path, "utf8")) as IconifyJSON;

  const base = resolve(ctx.cwd, options.out ?? "src/icons");
  // `src/icons.tsx` beside a written `src/icons.ts` would shadow it (or be shadowed): refuse instead.
  const clash = [".tsx", ".js", ".jsx"].map((ext) => base + ext).find((path) => existsSync(path));
  if (clash) {
    ctx.error(`${clash} already exists and would collide with ${base}.ts. Pick another path: --out src/icon-set`);
    return 1;
  }
  const header = `/*\n * GENERATED by \`skryensya icons ${preset.prefix}\`, do not edit by hand.\n *\n * ${preset.licence}, from @iconify-json/${preset.prefix}.\n */`;
  const set = iconSetFromIconify(json, preset, { components: options.components });
  const files: [string, string][] = [
    [`${base}.ts`, iconSetModule(set, header)],
    [`${base}.css`, `${header}\n${iconSetCss(set)}`],
  ];

  if (options.check) {
    const stale = files.filter(([path, text]) => !existsSync(path) || readFileSync(path, "utf8") !== text);
    if (stale.length) {
      ctx.error(`✗ ${stale.map(([path]) => path).join(", ")} out of date; run: skryensya icons ${prefix}${options.out ? ` --out ${options.out}` : ""}${options.components ? " --components" : ""}`);
      return 1;
    }
    ctx.log(`✓ ${preset.prefix}: ${Object.keys(set).length} icons up to date`);
    return 0;
  }

  for (const [path, text] of files) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    ctx.log(`  wrote  ${path}`);
  }
  if (options.usage === false) return 0;
  ctx.log();
  ctx.log("Use");
  ctx.log(`  React    <IconSetProvider set={icons}> from @skryensya/react/icon`);
  ctx.log(`  Vanilla  mountIcons(document, icons) from @skryensya/vanilla/icon`);
  ctx.log(`  and import the .css once: it draws the native select and carousel icons.`);
  return 0;
}

/** Node's own lookup for a package file: `node_modules/<rel>` here, then in each parent directory. */
function findUp(from: string, rel: string): string | undefined {
  for (let dir = from; ; dir = dirname(dir)) {
    if (existsSync(join(dir, rel))) return join(dir, rel);
    if (dirname(dir) === dir) return undefined;
  }
}
